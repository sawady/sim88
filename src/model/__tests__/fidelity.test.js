// Fidelity corpus: every program in tests/fidelity/programs is compared with
// what the original MSX88 / ASM88 did with it (golden files recorded by
// tools/oracle). See docs/fidelity.md.
//
// A program either matches the oracle, or is listed in
// tests/fidelity/known-differences.json with the reason. A listed program
// that starts matching fails too, so the list stays honest.
//
// `UPDATE_FIDELITY=1 npx vitest run fidelity` rewrites the summary in
// docs/fidelity.md; without it the test checks the summary is up to date.
import fs from 'node:fs';
import path from 'node:path';
import { describe, test, expect } from 'vitest';
import { loadCorpus, compareProgram, initialMemory, FIDELITY_DIR, FIDELITY_ALU_MODE } from '../../../tests/fidelity/compare';
import { DEFAULT_ALU_MODE } from '../alu';

const corpus = loadCorpus();
const initial = initialMemory();
const known = JSON.parse(fs.readFileSync(path.join(FIDELITY_DIR, 'known-differences.json'), 'utf8'));
const DOC = path.resolve(FIDELITY_DIR, '../../docs/fidelity.md');

const results = corpus.filter((entry) => entry.meta.compare !== 'no').map((entry) => ({ ...entry, diffs: entry.golden ? compareProgram(entry, initial) : null }));

// FIDELITY_REPORT=1 prints every difference.
if (process.env.FIDELITY_REPORT) {
  for (const r of results) if (r.diffs?.length) console.log(`\n${r.name}\n  ${r.diffs.join('\n  ')}`);
}

describe('fidelity corpus vs the MSX88 oracle', () => {
  test('the corpus runs with the ALU as MSX88, the default setting', () => {
    expect(FIDELITY_ALU_MODE).toBe('msx88');
    expect(DEFAULT_ALU_MODE).toBe('msx88');
  });

  test('every program has a golden file from the oracle', () => {
    expect(results.filter((r) => !r.golden).map((r) => r.name)).toEqual([]);
  });

  test('known differences only name programs of the corpus', () => {
    const names = new Set(corpus.map((c) => c.name));
    expect(Object.keys(known).filter((n) => !names.has(n))).toEqual([]);
  });

  for (const { name, diffs } of results.filter((r) => r.golden)) {
    if (known[name]) {
      test(`${name}: differs (${known[name].kind}): ${known[name].reason}`, () => {
        expect(diffs, `${name} matches MSX88 now: remove it from known-differences.json`).not.toEqual([]);
      });
    } else {
      test(`${name} matches MSX88`, () => {
        expect(diffs).toEqual([]);
      });
    }
  }

  test('docs/fidelity.md summary is up to date', () => {
    const compared = results.filter((r) => r.golden);
    const matching = compared.filter((r) => r.diffs.length === 0).length;
    const onPurpose = compared.filter((r) => known[r.name]?.kind === 'on purpose').length;
    const pending = compared.filter((r) => known[r.name]?.kind === 'pending').length;
    const summary = [
      '<!-- fidelity-summary:start (generated by UPDATE_FIDELITY=1 npx vitest run fidelity) -->',
      `**${matching} of ${compared.length} programs match MSX88.** Differences: ${onPurpose} on purpose, ${pending} pending.`,
      '',
      '| Program | Result |',
      '|---|---|',
      ...compared.map((r) =>
        r.diffs.length === 0
          ? `| \`${r.name}\` | identical |`
          : `| \`${r.name}\` | differs${known[r.name] ? ` (${known[r.name].kind})` : ''}: ${known[r.name]?.reason ?? r.diffs[0]} |`
      ),
      '<!-- fidelity-summary:end -->',
    ].join('\n');
    const doc = fs.readFileSync(DOC, 'utf8');
    const updated = doc.replace(/<!-- fidelity-summary:start[\s\S]*?<!-- fidelity-summary:end -->/, summary);
    if (process.env.UPDATE_FIDELITY) fs.writeFileSync(DOC, updated);
    else expect(doc).toBe(updated);
  });
});
